import { useCallback, useEffect, useMemo, useState } from 'react';
import { Link } from 'react-router-dom';
import { BarChart3, Brain, Clock, Eye, Puzzle, Search, Send, Sparkles, Trash2, Users } from 'lucide-react';
import { quizApi } from '../../api/endpoints';
import {
  Alert,
  Badge,
  Button,
  Card,
  EmptyState,
  PageLoader,
  ProgressBar,
  SectionTitle,
  StatCard,
  Tabs,
  toast,
} from '../../components/ui';
import { formatDate, formatDateTime, humanise, pct } from '../../utils/format';

const DIFFICULTY_TONES = { easy: 'success', medium: 'warning', hard: 'danger' };

export default function TeacherQuizzes() {
  const [quizzes, setQuizzes] = useState([]);
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState('');
  const [tab, setTab] = useState('all');
  const [search, setSearch] = useState('');
  const [busy, setBusy] = useState('');

  const load = useCallback(() => {
    setLoading(true);
    quizApi
      .list()
      .then((result) => setQuizzes(result.data || []))
      .catch((requestError) => setError(requestError.message))
      .finally(() => setLoading(false));
  }, []);

  useEffect(() => {
    load();
  }, [load]);

  const filtered = useMemo(() => {
    const needle = search.trim().toLowerCase();
    return quizzes.filter((quiz) => {
      const matches = !needle || [quiz.title, quiz.subject?.name, quiz.topic, quiz.unit].filter(Boolean).join(' ').toLowerCase().includes(needle);
      if (!matches) return false;
      if (tab === 'published') return quiz.status === 'published';
      if (tab === 'drafts') return quiz.status === 'draft';
      if (tab === 'ai') return quiz.aiGenerated;
      return true;
    });
  }, [quizzes, search, tab]);

  const publish = async (quiz) => {
    setBusy(quiz._id);
    try {
      await quizApi.update(quiz._id, { status: quiz.status === 'published' ? 'draft' : 'published' });
      toast(quiz.status === 'published' ? 'Quiz moved to drafts' : 'Quiz published — students can attempt it now', 'success');
      load();
    } catch (publishError) {
      toast(publishError.message, 'error');
    } finally {
      setBusy('');
    }
  };

  const remove = async (quiz) => {
    if (!window.confirm(`Delete "${quiz.title}" along with every attempt?`)) return;
    try {
      await quizApi.remove(quiz._id);
      toast('Quiz deleted', 'success');
      load();
    } catch (removeError) {
      toast(removeError.message, 'error');
    }
  };

  const totalAttempts = quizzes.reduce((sum, quiz) => sum + (quiz.stats?.attemptCount || 0), 0);
  const averageScore = quizzes.filter((quiz) => quiz.stats?.averageScore).length
    ? Math.round(
        (quizzes.filter((quiz) => quiz.stats?.averageScore).reduce((sum, quiz) => sum + quiz.stats.averageScore, 0) /
          quizzes.filter((quiz) => quiz.stats?.averageScore).length) *
          10
      ) / 10
    : 0;

  return (
    <div className="space-y-6">
      <SectionTitle
        title="AI Quizzes & Assessments"
        subtitle="Everything generated by the AI question engine, with live attempt analytics"
        action={
          <Link to="/teacher/ai-generator" className="btn-primary">
            <Sparkles size={16} /> Generate quiz
          </Link>
        }
      />

      {error ? <Alert tone="danger" title="Could not load quizzes">{error}</Alert> : null}

      <div className="grid gap-4 sm:grid-cols-2 xl:grid-cols-4">
        <StatCard label="Quizzes" value={quizzes.length} hint={`${quizzes.filter((quiz) => quiz.aiGenerated).length} AI generated`} icon={Puzzle} tone="brand" />
        <StatCard label="Published" value={quizzes.filter((quiz) => quiz.status === 'published').length} icon={Send} tone="success" />
        <StatCard label="Attempts" value={totalAttempts} hint="Across all quizzes" icon={Users} tone="info" />
        <StatCard label="Average score" value={pct(averageScore)} icon={BarChart3} tone="purple" />
      </div>

      <div className="flex flex-wrap items-center justify-between gap-3">
        <Tabs
          active={tab}
          onChange={setTab}
          tabs={[
            { value: 'all', label: 'All', count: quizzes.length },
            { value: 'published', label: 'Published' },
            { value: 'drafts', label: 'Drafts' },
            { value: 'ai', label: 'AI generated' },
          ]}
        />
        <div className="relative w-full max-w-xs">
          <Search size={15} className="pointer-events-none absolute left-3 top-3.5 text-ink-400" />
          <input className="input pl-9" placeholder="Search quizzes…" value={search} onChange={(event) => setSearch(event.target.value)} />
        </div>
      </div>

      {loading ? (
        <PageLoader />
      ) : filtered.length ? (
        <div className="grid gap-5 lg:grid-cols-2">
          {filtered.map((quiz) => (
            <Card key={quiz._id} className="flex flex-col">
              <div className="flex items-start justify-between gap-3 p-5">
                <div className="flex items-start gap-3">
                  <span className="grid h-11 w-11 shrink-0 place-items-center rounded-2xl bg-purple-50 text-purple-600">
                    <Brain size={20} />
                  </span>
                  <div>
                    <h3 className="font-semibold text-ink-900">{quiz.title}</h3>
                    <p className="text-xs text-ink-500">
                      {quiz.subject?.name || 'Subject'} · {humanise(quiz.paperType || 'quiz')}
                      {quiz.unit ? ` · ${quiz.unit}` : ''}
                      {quiz.topic ? ` · ${quiz.topic}` : ''}
                    </p>
                  </div>
                </div>
                <div className="flex flex-col items-end gap-1.5">
                  <Badge tone={quiz.status === 'published' ? 'success' : 'neutral'}>{quiz.status}</Badge>
                  <Badge tone={DIFFICULTY_TONES[quiz.difficulty] || 'neutral'}>{quiz.difficulty}</Badge>
                </div>
              </div>

              <div className="grid grid-cols-4 gap-2 px-5 pb-4 text-center">
                {[
                  ['Questions', quiz.questionCount || quiz.questions?.length || 0],
                  ['Marks', quiz.totalMarks],
                  ['Minutes', quiz.durationMinutes],
                  ['Attempts', quiz.stats?.attemptCount || 0],
                ].map(([label, value]) => (
                  <div key={label} className="rounded-xl bg-ink-50 py-2">
                    <p className="text-base font-bold text-ink-900">{value}</p>
                    <p className="text-[11px] uppercase tracking-wide text-ink-500">{label}</p>
                  </div>
                ))}
              </div>

              <div className="space-y-3 px-5 pb-4">
                {quiz.stats?.attemptCount ? (
                  <div>
                    <div className="mb-1 flex justify-between text-xs text-ink-500">
                      <span>Class average</span>
                      <span className="font-semibold text-ink-700">{pct(quiz.stats.averageScore)}</span>
                    </div>
                    <ProgressBar value={quiz.stats.averageScore} height="h-1.5" />
                  </div>
                ) : (
                  <p className="text-xs text-ink-400">No attempts yet</p>
                )}
                <div className="flex flex-wrap gap-x-4 gap-y-1 text-xs text-ink-500">
                  <span className="flex items-center gap-1">
                    <Clock size={12} /> {quiz.dueDate ? `Due ${formatDate(quiz.dueDate)}` : 'No deadline'}
                  </span>
                  <span>Created {formatDateTime(quiz.createdAt)}</span>
                  {quiz.stats?.pendingGrading ? <span className="font-semibold text-warning-600">{quiz.stats.pendingGrading} need review</span> : null}
                </div>
              </div>

              <div className="mt-auto flex flex-wrap gap-2 border-t border-ink-100 p-4">
                <Link to={`/teacher/quizzes/${quiz._id}`} className="btn-primary btn-sm">
                  <Eye size={14} /> Analytics
                </Link>
                <Button size="sm" variant="secondary" icon={Send} loading={busy === quiz._id} onClick={() => publish(quiz)}>
                  {quiz.status === 'published' ? 'Unpublish' : 'Publish'}
                </Button>
                <Link to={`/teacher/ai-generator?subject=${quiz.subject?._id || ''}`} className="btn-ghost btn-sm">
                  <Sparkles size={14} /> Regenerate
                </Link>
                <button onClick={() => remove(quiz)} className="btn-ghost btn-sm ml-auto text-danger-600 hover:bg-danger-50">
                  <Trash2 size={14} />
                </button>
              </div>
            </Card>
          ))}
        </div>
      ) : (
        <Card>
          <EmptyState
            icon={Brain}
            title="No quizzes yet"
            message="Use the AI generator to build a quiz in seconds — pick a subject, unit, difficulty and question count."
            action={
              <Link to="/teacher/ai-generator" className="btn-primary">
                <Sparkles size={15} /> Open AI generator
              </Link>
            }
          />
        </Card>
      )}
    </div>
  );
}
