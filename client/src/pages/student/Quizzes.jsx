import { useEffect, useMemo, useState } from 'react';
import { Link } from 'react-router-dom';
import { Award, Brain, CheckCircle2, Clock, History, Play, Sparkles, Target, TrendingUp } from 'lucide-react';
import { quizApi } from '../../api/endpoints';
import {
  Alert,
  Badge,
    Card,
  CardHeader,
  EmptyState,
  PageLoader,
  ProgressBar,
  SectionTitle,
  StatCard,
  Tabs,
} from '../../components/ui';
import { DonutChart, PerformanceTrendChart, TopicRadarChart } from '../../components/charts';
import { formatDateTime, gradeColor, humanise, percentageColor, pct } from '../../utils/format';

export default function StudentQuizzes() {
  const [quizzes, setQuizzes] = useState([]);
  const [attempts, setAttempts] = useState(null);
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState('');
  const [tab, setTab] = useState('available');

  useEffect(() => {
    Promise.all([quizApi.list(), quizApi.myAttempts()])
      .then(([quizResult, attemptResult]) => {
        setQuizzes(quizResult.data || []);
        setAttempts(attemptResult.data);
      })
      .catch((requestError) => setError(requestError.message))
      .finally(() => setLoading(false));
  }, []);

  const { available, completed } = useMemo(() => {
    const attemptedIds = new Set((attempts?.attempts || []).map((attempt) => attempt.quiz?._id).filter(Boolean));
    return {
      available: quizzes.filter((quiz) => quiz.canAttempt && !attemptedIds.has(quiz._id)),
      completed: attempts?.attempts || [],
    };
  }, [quizzes, attempts]);

  if (loading) return <PageLoader />;

  const summary = attempts?.summary || {};

  return (
    <div className="space-y-6">
      <SectionTitle
        title="AI Quizzes & Assessments"
        subtitle="Topic-wise quizzes generated by your teachers with instant scoring and feedback"
      />

      {error ? <Alert tone="danger" title="Could not load assessments">{error}</Alert> : null}

      <div className="grid gap-4 sm:grid-cols-2 xl:grid-cols-4">
        <StatCard label="Available now" value={available.length} hint="Ready to attempt" icon={Brain} tone="purple" />
        <StatCard label="Attempts" value={summary.completed || 0} hint={`${summary.total || 0} total records`} icon={History} tone="brand" />
        <StatCard
          label="Average score"
          value={pct(summary.average || 0)}
          hint="Across all completed quizzes"
          icon={Target}
          tone="info"
          trend={<ProgressBar value={summary.average || 0} />}
        />
        <StatCard label="Best score" value={pct(summary.best || 0)} hint="Personal best" icon={Award} tone="success" />
      </div>

      <Tabs
        active={tab}
        onChange={setTab}
        tabs={[
          { value: 'available', label: 'Available', icon: Play, count: available.length },
          { value: 'history', label: 'My attempts', icon: History, count: completed.length },
          { value: 'performance', label: 'Performance', icon: TrendingUp },
        ]}
      />

      {tab === 'available' ? (
        available.length ? (
          <div className="grid gap-4 lg:grid-cols-2 xl:grid-cols-3">
            {available.map((quiz) => (
              <Card key={quiz._id} className="flex flex-col">
                <div className="p-5">
                  <div className="flex items-start justify-between gap-3">
                    <span className="grid h-10 w-10 place-items-center rounded-xl bg-brand-50 text-brand-600">
                      <Brain size={18} />
                    </span>
                    <div className="flex flex-wrap justify-end gap-1.5">
                      <Badge tone="brand">{humanise(quiz.paperType)}</Badge>
                      <Badge tone="neutral">{humanise(quiz.difficulty)}</Badge>
                    </div>
                  </div>
                  <Link to={`/student/quizzes/${quiz._id}`} className="mt-3 block text-base font-semibold text-ink-900 hover:text-brand-600">
                    {quiz.title}
                  </Link>
                  <p className="mt-1 text-xs text-ink-500">
                    {quiz.subject?.name} {quiz.unit ? `· ${quiz.unit}` : ''}
                  </p>
                  {quiz.topic ? <p className="mt-2 line-clamp-2 text-xs text-ink-500">Topics: {quiz.topic}</p> : null}

                  <div className="mt-4 grid grid-cols-3 gap-2 text-center text-xs">
                    <div className="rounded-lg bg-ink-50 py-2">
                      <p className="font-bold text-ink-800">{quiz.questionCount}</p>
                      <p className="text-ink-500">Questions</p>
                    </div>
                    <div className="rounded-lg bg-ink-50 py-2">
                      <p className="font-bold text-ink-800">{quiz.totalMarks}</p>
                      <p className="text-ink-500">Marks</p>
                    </div>
                    <div className="rounded-lg bg-ink-50 py-2">
                      <p className="font-bold text-ink-800">{quiz.durationMinutes}m</p>
                      <p className="text-ink-500">Duration</p>
                    </div>
                  </div>
                </div>

                <div className="mt-auto flex items-center justify-between gap-3 border-t border-ink-100 p-4">
                  <span className="flex items-center gap-1.5 text-xs text-ink-500">
                    <Clock size={13} /> {quiz.dueDate ? `Due ${formatDateTime(quiz.dueDate)}` : 'No deadline'}
                  </span>
                  <Link to={`/student/quizzes/${quiz._id}`} className="btn-primary btn-sm">
                    <Play size={14} /> Start
                  </Link>
                </div>
              </Card>
            ))}
          </div>
        ) : (
          <Card>
            <EmptyState
              icon={Sparkles}
              title="No assessments available right now"
              message="When your teacher publishes an AI generated quiz it will appear here."
            />
          </Card>
        )
      ) : null}

      {tab === 'history' ? (
        <div className="table-wrapper">
          <table className="table">
            <thead>
              <tr>
                <th>Quiz</th>
                <th>Subject</th>
                <th>Submitted</th>
                <th>Score</th>
                <th>Percentage</th>
                <th>Grade</th>
                <th />
              </tr>
            </thead>
            <tbody>
              {completed.length ? (
                completed.map((attempt) => (
                  <tr key={attempt._id}>
                    <td className="font-medium text-ink-800">{attempt.quiz?.title || 'Quiz'}</td>
                    <td>{attempt.quiz?.subject?.shortName || attempt.quiz?.subject?.name || '—'}</td>
                    <td>{formatDateTime(attempt.submittedAt)}</td>
                    <td>
                      {attempt.score}/{attempt.totalMarks}
                    </td>
                    <td className={percentageColor(attempt.percentage)}>{pct(attempt.percentage)}</td>
                    <td>
                      <Badge className={gradeColor(attempt.grade)}>{attempt.grade}</Badge>
                    </td>
                    <td>
                      <Link to={`/student/quizzes/${attempt.quiz?._id}`} className="btn-ghost btn-sm">
                        Review
                      </Link>
                    </td>
                  </tr>
                ))
              ) : (
                <tr>
                  <td colSpan={7}>
                    <EmptyState icon={History} title="No attempts yet" message="Attempt your first AI quiz to see results here." />
                  </td>
                </tr>
              )}
            </tbody>
          </table>
        </div>
      ) : null}

      {tab === 'performance' ? (
        <div className="grid gap-5 xl:grid-cols-2">
          <Card>
            <CardHeader title="Score progression" subtitle="Your last 10 attempts" icon={TrendingUp} />
            <div className="p-4">
              <PerformanceTrendChart data={(summary.trend || []).map((entry) => ({ month: entry.label, percentage: entry.percentage }))} />
            </div>
          </Card>

          <Card>
            <CardHeader title="Topic mastery" subtitle="Accuracy by topic across all attempts" icon={Target} />
            <div className="p-4">
              <TopicRadarChart data={(summary.topicScores || []).slice(0, 8)} />
            </div>
          </Card>

          <Card>
            <CardHeader title="Result distribution" subtitle="Attempts grouped by score band" icon={CheckCircle2} />
            <div className="p-4">
              <DonutChart
                data={[
                  { name: '80-100%', value: completed.filter((a) => a.percentage >= 80).length, color: '#10b981' },
                  { name: '60-79%', value: completed.filter((a) => a.percentage >= 60 && a.percentage < 80).length, color: '#6366f1' },
                  { name: '40-59%', value: completed.filter((a) => a.percentage >= 40 && a.percentage < 60).length, color: '#f59e0b' },
                  { name: 'Below 40%', value: completed.filter((a) => a.percentage < 40).length, color: '#ef4444' },
                ]}
                centerValue={pct(summary.average || 0)}
                centerLabel="Average"
              />
            </div>
          </Card>

          <Card>
            <CardHeader title="Topic-wise accuracy" subtitle="Where you are strong and where you need practice" icon={Brain} />
            <div className="space-y-3 p-5">
              {(summary.topicScores || []).length ? (
                (summary.topicScores || []).map((topic) => (
                  <div key={topic.topic}>
                    <div className="mb-1 flex items-center justify-between text-sm">
                      <span className="truncate font-medium text-ink-700">{topic.topic}</span>
                      <span className="shrink-0 text-xs text-ink-500">
                        {topic.correct}/{topic.total} correct · {topic.percentage}%
                      </span>
                    </div>
                    <ProgressBar value={topic.percentage} height="h-1.5" />
                  </div>
                ))
              ) : (
                <EmptyState icon={Target} title="No topic data yet" message="Attempt a quiz to build your topic profile." />
              )}
            </div>
          </Card>
        </div>
      ) : null}
    </div>
  );
}
